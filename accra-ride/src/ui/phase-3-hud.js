(()=>{
  const speed=document.getElementById("speed");
  const mission=document.getElementById("mission");
  const panel=document.getElementById("driveReadout");
  const gear=document.getElementById("gearReadout");
  const distance=document.getElementById("distanceReadout");
  const unit=document.getElementById("distanceUnit");
  const signal=document.getElementById("signalReadout");
  const cover=document.getElementById("startcover");
  if(!speed||!mission||!panel||!gear||!distance||!unit||!signal)return;
  const clamp=(n,min,max)=>Math.min(max,Math.max(min,n));
  const sync=()=>{
    const status=mission.textContent||"";
    const speedValue=clamp(Number(speed.textContent)||0,0,180);
    const percent=speedValue/180*100;
    panel.style.setProperty("--speed-p",percent.toFixed(1));
    panel.style.setProperty("--speed-fill",percent.toFixed(1)+"%");
    const reversing=status.startsWith("REVERSE GEAR");
    const drive=status.startsWith("DRIVE");
    gear.textContent=reversing?"R":"D";
    panel.dataset.gear=reversing?"R":"D";
    const trip=status.match(/(\d+)\s*m\s*$/i);
    const metres=trip?Number(trip[1]):0;
    const shown=metres>=1000?(metres/1000).toFixed(2):String(metres);
    distance.textContent=shown;
    unit.textContent=metres>=1000?"km":"m";
    const phase=status.includes("AMBER LIGHT")?"1":status.includes("GREEN LIGHT")?"2":"0";
    const label=phase==="1"?"AMBER":phase==="2"?"GREEN":"RED";
    const near=phase==="0"&&status.includes("RED LIGHT AHEAD");
    signal.dataset.phase=phase;
    signal.dataset.near=near?"1":"0";
    signal.setAttribute("aria-label","Traffic signal: "+label.toLowerCase()+(near?", red light ahead":""));
    const signalLabel=signal.querySelector(".ar-signal-label");
    if(signalLabel)signalLabel.textContent=label;
    const menuOpen=!!cover&&cover.style.display!=="none";
    const running=drive||reversing;
    const engineError=status.includes("3D engine could not load");
    panel.dataset.live=running&&!menuOpen&&!engineError?"1":"0";
  };
  const observer=new MutationObserver(sync);
  observer.observe(speed,{childList:true,characterData:true,subtree:true});
  observer.observe(mission,{childList:true,characterData:true,subtree:true});
  if(cover)new MutationObserver(sync).observe(cover,{attributes:true,attributeFilter:["style","class","aria-hidden"]});
  document.addEventListener("accrarush:show-menu",sync);
  sync();
})();