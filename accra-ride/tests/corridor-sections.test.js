import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

test("Lapaz–Madina section inventory reconciles with the approved OSM route", async t => {
  let sections, route;
  try {
    [sections,route]=await Promise.all([
      readFile(new URL("../data/osm/lapaz-madina-sections.json",import.meta.url),"utf8").then(JSON.parse),
      readFile(new URL("../data/osm/lapaz-madina-route.json",import.meta.url),"utf8").then(JSON.parse)
    ]);
  } catch { t.skip("section inventory is generated by the corridor import workflow"); return; }
  if(sections.schemaVersion<2 || !sections.sections[0]?.roadArrangement){ t.skip("expanded opposing-carriageway inventory is regenerated by the OSM import workflow"); return; }
  assert.equal(sections.routeId,route.routeId);
  assert.equal(sections.alignment.closed,false);
  assert.equal(sections.alignment.stepCount,route.stepCount);
  assert.equal(sections.sectionCount,sections.sections.length);
  assert.ok(sections.sections.length>=2);
  assert.ok(Math.abs(sections.sections.reduce((sum,s)=>sum+s.distanceM,0)-sections.alignment.distanceM)<1);
  assert.deepEqual(sections.alignment.namedRoads,route.namedRoads);
  assert.ok(sections.sections.some(section=>section.name.includes("George Walker Bush Highway") && section.roadArrangement==="divided-dual-carriageway"),"N1 must preserve both separated carriageways");
  assert.ok(sections.sections.some(section=>section.name.includes("J.J. Rawlings Avenue") && section.opposingEdgeCount>0),"N4 must report its opposing carriageway arrangement");
  const interchange=sections.sections.find(section=>section.name==="Tetteh Quarshie Interchange");
  assert.ok(interchange && interchange.connectorCount>=20,"Tetteh Quarshie must include its bounded interchange ramps and crossing roads");
  assert.ok(interchange.connectorRoadNames.includes("Liberation Road"));
  assert.ok(interchange.connectorRoadNames.includes("Spintex Road"));
  assert.ok(interchange.connectorHighwayCounts.motorway_link>0 && interchange.connectorHighwayCounts.trunk_link>0);
  for(const section of sections.sections){
    assert.ok(section.edgeCount>0);
    assert.ok(section.distanceM>0);
    assert.ok(section.start && section.end);
    assert.ok(Object.keys(section.laneLayouts).length>0);
    assert.ok(section.osmWayIds.length>0);
    assert.ok(["explicitly-tagged-in-source","measured-from-opposing-paired-carriageways","not-mapped-in-source"].includes(section.medianStatus));
    assert.ok(Array.isArray(section.pairedWayIds));
    assert.ok(["divided-dual-carriageway","mixed-carriageway","shared-two-way-carriageway","single-direction-carriageway"].includes(section.roadArrangement));
    assert.ok(Array.isArray(section.opposingWayIds));
    assert.ok(section.opposingLaneLayouts && typeof section.opposingLaneLayouts==="object");
    if(section.roadArrangement==="divided-dual-carriageway") assert.ok(section.opposingEdgeCount>0);
  }
});
