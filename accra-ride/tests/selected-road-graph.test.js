import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { selectHighwayRouteGraph, buildMapModel, directedComponents } from "../src/map/selected-road-graph.js";

test("Lapaz–Madina selected graph contains only the approved point-to-point OSM corridor", async t => {
  let sourceDoc, manifest;
  try {
    [sourceDoc,manifest]=await Promise.all([
      readFile(new URL("../data/osm/lapaz-routing.network.json",import.meta.url),"utf8").then(JSON.parse),
      readFile(new URL("../data/osm/lapaz-madina-route.json",import.meta.url),"utf8").then(JSON.parse)
    ]);
  } catch { t.skip("full Lapaz routing extract is generated by the OSM import workflow"); return; }
  const source=sourceDoc.network;
  const {network,report}=selectHighwayRouteGraph(source,manifest);
  assert.equal(report.connected,true);
  assert.equal(manifest.closed,false);
  assert.notEqual(manifest.startNodeId,manifest.endNodeId);
  assert.equal(report.waypointCount,2);
  assert.ok(network.edges.length<source.edges.length*0.2);
  const sourceById=new Map(source.edges.map(edge=>[edge.id,edge]));
  for(const edge of network.edges){
    assert.ok(sourceById.has(edge.id));
    assert.equal(edge.selection.role,"route");
    assert.deepEqual(edge.centerline,sourceById.get(edge.id).centerline);
    assert.deepEqual(edge.lanes,sourceById.get(edge.id).lanes);
  }
  const map=buildMapModel(network,"lapaz");
  assert.deepEqual(map.roads.map(road=>road.id),network.edges.map(edge=>edge.id));
  assert.ok(directedComponents(network.edges).length>0);
});
