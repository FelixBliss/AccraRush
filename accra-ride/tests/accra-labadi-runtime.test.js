class Group { constructor(){this.children=[];this.userData={};} add(child){this.children.push(child);} traverse(fn){fn(this);for(const child of this.children)fn(child);} }
class BufferGeometry { constructor(){this.attributes={};this.index=[];} setAttribute(n,v){this.attributes[n]=v;} setIndex(v){this.index=v;} computeVertexNormals(){} dispose(){} }
class Float32BufferAttribute { constructor(array,itemSize){this.array=array;this.itemSize=itemSize;} }
class Mesh { constructor(geometry,material){this.geometry=geometry;this.material=material;this.userData={};} }
class LineSegments extends Mesh {}
class Material { constructor(options){this.options=options;} dispose(){} }
const THREE={Group,BufferGeometry,Float32BufferAttribute,Mesh,LineSegments,MeshStandardMaterial:Material,LineBasicMaterial:Material};

test("Route 2 loads the approved Accra–Labadi OSM highway corridor", async (t) => {
  let document,route;
  try {
    [document,route]=await Promise.all([
      readFile(new URL("../data/osm/accra-central.network.json",import.meta.url),"utf8").then(JSON.parse),
      readFile(new URL("../data/osm/accra-labadi-route.json",import.meta.url),"utf8").then(JSON.parse)
    ]);
  } catch { t.skip("Route 2 OSM graph and manifest are generated by the dedicated import workflow"); return; }
  const scene={children:[],add(object){this.children.push(object);},remove(object){this.children=this.children.filter(item=>item!==object);}};
  const runtime=await loadRoadNetworkRuntime({THREE,scene,areaId:"accra-central",fetcher:async url=>({
    ok:true,json:async()=>url.split("?")[0].endsWith("accra-labadi-route.json")?route:document
  })});
  assert.equal(runtime.raceCircuit.closed,false);
  assert.equal(runtime.raceCircuit.startNodeId,route.startNodeId);
  assert.equal(runtime.raceCircuit.destinationNodeId,route.endNodeId);
  assert.notEqual(runtime.raceCircuit.startNodeId,runtime.raceCircuit.destinationNodeId);
  assert.equal(runtime.returnHighwayRoute.startNodeId,route.endNodeId);
  assert.equal(runtime.returnHighwayRoute.destinationNodeId,route.startNodeId);
  assert.deepEqual(runtime.featuredRoadNames,route.namedRoads);
  const approvedRoadNames = new Set(route.namedRoads.map(name=>name.toLowerCase()));
  assert.ok(route.returnNamedRoads.every(name=>approvedRoadNames.has(name.toLowerCase())),
    "Return journey must stay on the same approved Google Maps corridor, not use alternative streets");
  assert.ok(route.namedRoads.some(name=>/ring road east/i.test(name)), "Google Maps primary corridor must include Ring Road East");
  assert.ok(route.namedRoads.some(name=>/la road|la rd/i.test(name)), "Google Maps primary corridor must include La Road");
  const expectedMinimapEdges = [...new Set([...route.steps, ...route.returnSteps].map(step=>step.edgeId))].sort();
  assert.deepEqual(runtime.minimap.roads.map(road=>road.id).sort(), expectedMinimapEdges,
    "Route 2 minimap must show both outbound and return carriageways");
  assert.ok(runtime.minimap.routeEndpoints.start && runtime.minimap.routeEndpoints.end);
  assert.ok(runtime.network.edges.every(edge=>document.network.edges.some(source=>source.id===edge.id)));
  assert.ok(runtime.sample(runtime.raceCircuit,0)?.edge?.selection?.role==="route");
  runtime.dispose();
  assert.equal(scene.children.length,0);
});


test("Route 2 menu preview uses both directions while Lapaz remains outbound-only", async () => {
  const menu = await readFile(new URL("../src/ui/phase-2-navigation.js", import.meta.url), "utf8");
  assert.match(menu, /area==="accra-central"[\s\S]*?\[\.\.\.manifest\.steps,\.\.\.\(manifest\.returnSteps\|\|\[\]\)\]/,
    "Accra–Labadi menu preview must include outbound and return manifest edges");
  assert.match(menu, /:new Set\(manifest\.steps\.map\(step=>step\.edgeId\)\)/,
    "Lapaz menu preview must remain outbound-only");
  assert.match(menu, /mapModel\.roads=mapModel\.roads\.filter\(road=>previewIds\.has\(road\.id\)\)/,
    "the preview must render only the selected corridor edges");
});


test("Route 2 menu preview marks outbound and inbound directions at the Accra start junction", async () => {
  const menu = await readFile(new URL("../src/ui/phase-2-navigation.js", import.meta.url), "utf8");
  assert.match(menu, /outboundEdgeId:manifest\.steps\?\.\[0\]\?\.edgeId/,
    "the outbound arrow must use the first selected outbound edge");
  assert.match(menu, /inboundEdgeId:manifest\.returnSteps\?\.\[manifest\.returnSteps\.length-1\]\?\.edgeId/,
    "the inbound arrow must use the final return edge arriving at the start junction");
  assert.match(menu, /addArrow\(network\.previewDirections\.outboundEdgeId,false,"OUT"/,
    "the outbound arrow must point away from the start junction");
  assert.match(menu, /addArrow\(network\.previewDirections\.inboundEdgeId,true,"IN"/,
    "the inbound arrow must point toward the start junction");
  assert.match(menu, /data-direction/,
    "direction arrows must be identifiable in the rendered preview");
});
